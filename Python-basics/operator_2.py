
# Operators are used to perform operations on variables and values. In Python, there are several types of operators, including arithmetic operators, assignment operators, comparison operators, logical operators, bitwise operators, and more.
# Arithmetic Operators are used to perform mathematical operations on numbers. The basic arithmetic operators include addition (+), subtraction (-), multiplication (*), division (/), modulus (%), floor division (//), and exponentiation (**).

x=12
y=23
print(x+y) # Addition
print(x-y) # Subtraction    
print(x*y) # Multiplication
print(x/y) # Division  
print(x%y) # Modulus
print(x//y) # Floor Division // Floor Division is used to get the quotient of the division and it rounds down the result to the nearest integer.
print(x**y) # Exponentiation  // Exponentiation is used to raise a number to the power of another number. For example, 2**3 will give you 8, which is 2 raised to the power of 3.

